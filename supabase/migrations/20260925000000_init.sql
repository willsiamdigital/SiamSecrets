-- ---------------------------------------------------------------------------
-- Featured-slot auction (top 3 positions)
-- ---------------------------------------------------------------------------
create table public.auction_slots (
  position smallint primary key check (position between 1 and 3),
  listing_id bigint references public.listings on delete set null,
  current_bid_cents integer check (current_bid_cents > 0),
  starting_bid_cents integer not null default 5000 check (starting_bid_cents > 0),
  increment_cents integer not null default 500 check (increment_cents > 0),
  round_ends_at timestamptz not null,
  updated_at timestamptz not null default now()
);

insert into public.auction_slots (position, round_ends_at)
select p, now() + interval '7 days' from generate_series(1, 3) p;

alter table public.auction_slots enable row level security;

create policy "auction slots are public" on public.auction_slots
  for select to anon, authenticated using (true);

create policy "admins manage auction slots" on public.auction_slots
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

create table public.bids (
  id bigint generated by default as identity primary key,
  slot_position smallint not null references public.auction_slots on delete cascade,
  listing_id bigint not null references public.listings on delete cascade,
  bidder_id uuid not null references auth.users on delete cascade,
  amount_cents integer not null check (amount_cents > 0),
  created_at timestamptz not null default now()
);

create index bids_slot_idx on public.bids (slot_position, created_at desc);
create index bids_bidder_idx on public.bids (bidder_id, created_at desc);

alter table public.bids enable row level security;

-- No insert policy: bids are only written through place_bid().
create policy "bidders see their own bids" on public.bids
  for select to authenticated
  using (bidder_id = auth.uid() or public.is_admin());

-- Places a bid atomically. The slot row is locked so concurrent bids are
-- validated against the latest price. No money moves here: payment capture
-- for winning bids is a separate step.
create function public.place_bid(p_slot smallint, p_listing_id bigint, p_amount_cents integer)
returns public.auction_slots
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_slot public.auction_slots;
  v_min integer;
begin
  if v_uid is null then
    raise exception 'Sign in to place a bid' using errcode = '28000';
  end if;

  select * into v_slot from public.auction_slots where position = p_slot for update;
  if not found then
    raise exception 'Unknown auction slot' using errcode = 'P0002';
  end if;

  if now() >= v_slot.round_ends_at then
    raise exception 'Bidding for this slot has closed' using errcode = '22023';
  end if;

  if not exists (
    select 1 from public.listings
    where id = p_listing_id and owner_id = v_uid and status = 'approved'
  ) then
    raise exception 'You can only bid with one of your own approved listings' using errcode = '42501';
  end if;

  if exists (
    select 1 from public.auction_slots
    where listing_id = p_listing_id and position <> p_slot and current_bid_cents is not null
  ) then
    raise exception 'This listing already holds another featured slot' using errcode = '22023';
  end if;

  v_min := coalesce(v_slot.current_bid_cents + v_slot.increment_cents, v_slot.starting_bid_cents);
  if p_amount_cents is null or p_amount_cents < v_min then
    raise exception 'Minimum bid is €%', to_char(v_min / 100.0, 'FM999999990.00')
      using errcode = '22023';
  end if;
  if p_amount_cents % 100 <> 0 then
    raise exception 'Bids must be whole euros' using errcode = '22023';
  end if;

  insert into public.bids (slot_position, listing_id, bidder_id, amount_cents)
  values (p_slot, p_listing_id, v_uid, p_amount_cents);

  update public.auction_slots
  set listing_id = p_listing_id, current_bid_cents = p_amount_cents, updated_at = now()
  where position = p_slot
  returning * into v_slot;

  return v_slot;
end;
$$;

-- A listing that stops being public loses its featured slot; the slot reopens
-- at the starting bid.
create function public.listings_release_slot()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.auction_slots
  set listing_id = null, current_bid_cents = null, updated_at = now()
  where listing_id = new.id;
  return new;
end;
$$;

create trigger listings_release_slot
  after update of status on public.listings
  for each row when (old.status = 'approved' and new.status <> 'approved')
  execute function public.listings_release_slot();

revoke execute on function public.place_bid(smallint, bigint, integer) from public, anon;
grant execute on function public.place_bid(smallint, bigint, integer) to authenticated;

-- ---------------------------------------------------------------------------
-- Reports
-- ---------------------------------------------------------------------------
create table public.reports (
  id bigint generated by default as identity primary key,
  listing_id bigint not null references public.listings on delete cascade,
  reporter_id uuid default auth.uid() references auth.users on delete set null,
  reason text not null check (reason in (
    'underage', 'trafficking_or_coercion', 'fake_or_stolen_photos', 'spam_or_scam', 'other'
  )),
  details text not null default '' check (char_length(details) <= 1000),
  status text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  resolved_by uuid references auth.users on delete set null,
  resolved_at timestamptz,
  created_at timestamptz not null default now()
);

create index reports_open_idx on public.reports (status, created_at);

alter table public.reports enable row level security;

create policy "anyone can report a listing" on public.reports
  for insert to anon, authenticated
  with check (
    status = 'open'
    and resolved_by is null
    and reporter_id is not distinct from auth.uid()
  );

create policy "admins review reports" on public.reports
  for select to authenticated using (public.is_admin());

create policy "admins resolve reports" on public.reports
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- Reports of a minor or of coercion take the listing offline immediately,
-- pending admin review.
create function public.reports_auto_suspend()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.reason in ('underage', 'trafficking_or_coercion') then
    update public.listings set status = 'suspended', updated_at = now()
    where id = new.listing_id and status <> 'suspended';
  end if;
  return new;
end;
$$;

create trigger reports_auto_suspend
  after insert on public.reports
  for each row execute function public.reports_auto_suspend();

