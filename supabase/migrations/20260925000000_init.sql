-- Siam Secrets: listings, favourites, featured-slot auction, reports, moderation.
-- Money is stored in euro cents.

-- ---------------------------------------------------------------------------
-- Admins
-- ---------------------------------------------------------------------------
create table public.admins (
  user_id uuid primary key references auth.users on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admins enable row level security;

create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

create policy "admins can see the admin list" on public.admins
  for select to authenticated using (public.is_admin());

-- ---------------------------------------------------------------------------
-- Listings
-- ---------------------------------------------------------------------------
create type public.listing_status as enum ('pending', 'approved', 'rejected', 'suspended');
create type public.listing_tier as enum ('featured', 'directory');

create table public.listings (
  id bigint generated by default as identity primary key,
  owner_id uuid references auth.users on delete set null,
  name text not null check (char_length(btrim(name)) between 1 and 60),
  area text not null check (char_length(btrim(area)) between 1 and 60),
  age smallint not null check (age between 18 and 99),
  bio text not null default '' check (char_length(bio) <= 2000),
  image_url text not null check (image_url ~ '^https://'),
  availability text not null default 'Available' check (char_length(availability) <= 40),
  tier public.listing_tier not null default 'directory',
  status public.listing_status not null default 'pending',
  -- Set when the submitter confirms the advertised person is an adult who consents
  -- to the listing and that they have rights to the photos.
  adult_declared_at timestamptz not null,
  is_demo boolean not null default false,
  review_note text,
  reviewed_by uuid references auth.users on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index listings_public_idx on public.listings (status, tier, created_at desc);
create index listings_owner_idx on public.listings (owner_id);

-- Non-admin users can never set moderation fields themselves, and any edit to
-- the content of an approved listing sends it back to the review queue.
-- Rows written without a user session (migrations, seed, service role) and
-- writes made by other triggers (e.g. auto-suspension on reports) pass through.
create function public.listings_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null or public.is_admin() or pg_trigger_depth() > 1 then
    new.updated_at := now();
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.owner_id := auth.uid();
    new.status := 'pending';
    new.tier := 'directory';
    new.is_demo := false;
    new.review_note := null;
    new.reviewed_by := null;
    new.reviewed_at := null;
    new.created_at := now();
  else
    new.owner_id := old.owner_id;
    new.tier := old.tier;
    new.is_demo := old.is_demo;
    new.review_note := old.review_note;
    new.reviewed_by := old.reviewed_by;
    new.reviewed_at := old.reviewed_at;
    new.created_at := old.created_at;
    new.adult_declared_at := old.adult_declared_at;
    if (new.name, new.area, new.age, new.bio, new.image_url)
       is distinct from (old.name, old.area, old.age, old.bio, old.image_url)
       and old.status <> 'suspended' then
      new.status := 'pending';
    else
      new.status := old.status;
    end if;
  end if;

  new.updated_at := now();
  return new;
end;
$$;

create trigger listings_guard
  before insert or update on public.listings
  for each row execute function public.listings_guard();

alter table public.listings enable row level security;

create policy "approved listings are public" on public.listings
  for select to anon, authenticated
  using (status = 'approved' or owner_id = auth.uid() or public.is_admin());

create policy "signed-in users submit their own listings" on public.listings
  for insert to authenticated
  with check (owner_id = auth.uid() or public.is_admin());

create policy "owners and admins update listings" on public.listings
  for update to authenticated
  using (owner_id = auth.uid() or public.is_admin())
  with check (owner_id = auth.uid() or public.is_admin());

create policy "owners and admins delete listings" on public.listings
  for delete to authenticated
  using (owner_id = auth.uid() or public.is_admin());

-- Public directory search. Runs with the caller's permissions (RLS applies),
-- and only ever returns approved listings.
create function public.search_listings(p_query text default '', p_area text default null)
returns setof public.listings
language sql
stable
set search_path = ''
as $$
  select l.*
  from public.listings l
  where l.status = 'approved'
    and (coalesce(p_query, '') = ''
         or l.name ilike '%' || p_query || '%'
         or l.area ilike '%' || p_query || '%')
    and (p_area is null or l.area = p_area)
  order by l.tier, l.created_at desc, l.id;
$$;

